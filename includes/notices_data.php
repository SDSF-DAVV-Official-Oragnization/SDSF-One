// Helper to count by category
function getNoticeCounts($notices) {
    $counts = [
        'all' => count($notices),
        'examination' => 0,
        'results' => 0,
        'library' => 0,
        'phd' => 0,
        'admissions' => 0,
        'general' => 0
    ];
    foreach ($notices as $n) {
        $cat = $n['category'];
        if (isset($counts[$cat])) {
            $counts[$cat]++;
        } else {
            $counts[$cat] = 1;
        }
    }
    return $counts;
}
